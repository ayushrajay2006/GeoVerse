from langchain_core.messages import SystemMessage, HumanMessage

class ValidationAgent:
    def __init__(self, llm):
        self.llm = llm
        self.system_prompt = SystemMessage(content='''
You are the Validation Agent for GeoVerse.
Your job is to cross-check the analysis results generated by the Analysis Agent against the original spatial workflow plan and data retrieved.
Ensure there are no hallucinations or logical inconsistencies in the spatial reasoning.
If everything is consistent, output a JSON object with 'status': 'valid' and 'reasoning': 'your explanation'.
If there are inconsistencies, output 'status': 'invalid' and specify the 'reasoning'.
''')

    def validate(self, plan_json: str, data_json: str, analysis_json: str) -> str:
        prompt = f"Plan:\n{plan_json}\n\nData:\n{data_json}\n\nAnalysis Results:\n{analysis_json}\n\nPlease validate the spatial reasoning and return the JSON object."
        response = self.llm.invoke([self.system_prompt, HumanMessage(content=prompt)])
        return response.content
